"""Emit the coverage/spread table as LaTeX, straight from the result root.

Coverage is distinct standardized endpoints (rounded to 3 dp) over in-scope
analyses: how much of what an arm produced is actually a different answer
rather than the same one again. Spread is the 95% width as a percentage of
the human panel's own width on the same dataset.

Usage:  python -m scripts.make_coverage_table [--root results/final_v1]
                                              [--out paper/table_coverage_spread.tex]
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CROWD_CSV = REPO_ROOT / "research/scratch/manyecoevo/extracted/master_data.csv"
CROWD_NAME = {"bt": "blue tit", "eu": "eucalyptus"}
DATASET_LABEL = {"bt": "Blue tit", "eu": "Eucalyptus"}
# results/ directory suffix -> the name the paper uses
ARMS = [("naive", "Naive"), ("continuation", "Branchpoint"), ("spread", "BpDynamic")]


def quantile(values: list[float], p: float) -> float:
    values = sorted(values)
    i = (len(values) - 1) * p
    lo = int(i)
    return values[lo] if lo == i else values[lo] + (i - lo) * (values[lo + 1] - values[lo])


def crowd(ds: str) -> dict:
    """The human panel on the same Fisher-z scale the arms are placed on."""
    values = []
    for row in csv.DictReader(CROWD_CSV.open()):
        if row.get("dataset") != CROWD_NAME[ds] or row.get("split_id") != "1":
            continue
        try:
            beta, se, df = (
                float(row["beta_estimate"]), float(row["beta_SE"]), float(row["adjusted_df"])
            )
        except (TypeError, ValueError):
            continue
        if se <= 0 or df <= 3:
            continue
        t = beta / se
        r = t / math.sqrt(t * t + df)
        if abs(r) < 1:
            values.append(math.atanh(r))
    return {
        "n": len(values),
        "unique": len({round(v, 3) for v in values}),
        "width": quantile(values, .975) - quantile(values, .025),
    }


def costs(root: Path) -> dict[str, float]:
    """Total spend per condition, Layer 1 and its Layer-2 judging together."""
    spend: dict[str, float] = {}
    for path in root.rglob("costs.jsonl"):
        for line in path.read_text().splitlines():
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            name = row.get("cond")
            if name:
                name = name.removeprefix("std_")
                spend[name] = spend.get(name, 0.0) + (row.get("usd") or 0.0)
    return spend


def conditions(root: Path) -> dict:
    found = {}
    for path in sorted(root.glob("*/results_final.json")):
        name = path.parent.name
        ds, model, arm = name.split("_")[0], name.split("_")[1], name.split("_", 2)[2]
        result = json.loads(path.read_text())
        live = [
            row["estimate_standardized"] for row in result["rows"]
            if row.get("estimate_standardized") is not None and row.get("scope") == "E"
        ]
        if not live:
            continue
        found[(ds, model, arm)] = {
            "n": len(live),
            "unique": result["unique_ends"],
            "width": quantile(live, .975) - quantile(live, .025),
        }
    return found


MODEL_LABEL = {"sol": "gpt-5.6-sol", "opus": "claude-opus-5", "glm": "glm-5.3"}


def verdict(found: dict) -> str:
    """State the BpDynamic-vs-Branchpoint width comparison from the numbers, so
    the caption cannot drift from the table above it."""
    wider = both = 0
    for (ds, model, arm), got in found.items():
        if arm != "spread":
            continue
        base = found.get((ds, model, "continuation"))
        if not base:
            continue
        both += 1
        wider += got["width"] > base["width"]
    return (
        f"Against Branchpoint on the same cell, BpDynamic is wider in {wider} of "
        f"{both}; on Eucalyptus the widths separate the arms, on blue tit they "
        f"do not.}}"
    )


def render(root: Path) -> str:
    found = conditions(root)
    spend = costs(root)
    panels = {ds: crowd(ds) for ds in ("bt", "eu")}
    models = ("sol", "opus", "glm")
    lines = [
        "% Generated by scripts/make_coverage_table.py -- do not hand-edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\begin{tabular}{llrr}",
        "\\toprule",
        "Sampling & Model & Width & \\$/unique \\\\",
        "\\midrule",
    ]
    for ds in ("bt", "eu"):
        panel = panels[ds]
        lines.append(
            f"\\multicolumn{{4}}{{l}}{{\\textbf{{{DATASET_LABEL[ds]}}}}} \\\\"
        )
        lines.append(
            f"\\quad Human & --- & {panel['width']:.2f} & --- \\\\"
        )
        lines.append("\\addlinespace[2pt]")
        for arm, arm_label in ARMS:
            rows = [(m, found[(ds, m, arm)]) for m in models if (ds, m, arm) in found]
            for i, (model, got) in enumerate(rows):
                # the arm is named once and blank on its continuation rows, so the
                # eye groups by sampling without a rule between blocks
                label = f"\\quad {arm_label}" if i == 0 else ""
                usd = spend.get(f"{ds}_{model}_{arm}")
                per = f"{usd / got['unique']:.2f}" if usd and got["unique"] else "---"
                lines.append(
                    f"{label} & {MODEL_LABEL[model]} & "
                    f"{got['width']:.2f} & {per} \\\\"
                )
            if rows:
                lines.append("\\addlinespace[2pt]")
        if ds == "bt":
            lines.append("\\midrule")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Width and cost by sampling arm, $n=50$ per condition. "
        "\\emph{Width} is the 95\\% window of the "
        "Fisher-$z$ distribution, in absolute units, so the human panel is directly "
        "comparable. \\emph{\\$/unique} is total spend for the condition, Layer 1 and "
        "its Layer-2 judging together, divided by the number of distinct endpoints it "
        "bought; the human panel has no comparable figure. " + verdict(found),
        "\\label{tab:coverage-spread}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="results/final_v1")
    parser.add_argument("--out", default="paper/table_coverage_spread.tex")
    args = parser.parse_args()
    out = REPO_ROOT / args.out
    out.write_text(render(REPO_ROOT / args.root))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
